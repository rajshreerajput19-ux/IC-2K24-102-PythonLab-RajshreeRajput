# Question 4: List Slicing

li = [1, 2, 4, 3]

# General syntax: li[start:end:step]

# (a) Elements at index 1 and 2
print(li[1:3])

# (b) Elements from index 2 onward
print(li[2:])

# (c) Elements up to index 3
print(li[:3])

# (d) Every other element
print(li[::2])

# (e) Reversed list
print(li[::-1])
